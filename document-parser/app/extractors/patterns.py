"""Регулярные выражения для российских деловых документов."""
import re

# Налоговые идентификаторы
RE_INN = re.compile(r"\b\d{10}\b|\b\d{12}\b")
RE_KPP = re.compile(r"\b\d{4}[\dA-Z]{2}\d{3}\b")
RE_OGRN = re.compile(r"\b\d{13}\b|\b\d{15}\b")

# Банковские реквизиты
RE_BIK = re.compile(r"\b04\d{7}\b")
RE_ACCOUNT = re.compile(r"\b\d{20}\b")

# Суммы:
#   1) с пробелами-разделителями групп: 1 234 567,89 руб.
#   2) с точкой: 12345.67 RUB
# Валюты: руб, руб., рубль, рублей, ₽, RUB
_SUM_BODY = r"(?:\d{1,3}(?:[  ]\d{3})+|\d+)(?:[.,]\d{1,2})?"
RE_AMOUNT = re.compile(
    rf"({_SUM_BODY})\s*(руб(?:лей|ля|\.)?|₽|RUB)(?=\b|[\s.,;:)]|$)",
    re.IGNORECASE,
)

# Даты:
#   1) DD.MM.YYYY, DD/MM/YYYY, DD-MM-YYYY
#   2) словесные: 25 мая 2026
RE_DATE_NUM = re.compile(r"\b(\d{1,2})[./-](\d{1,2})[./-](\d{2,4})\b")
RE_DATE_WORD = re.compile(
    r"\b(\d{1,2})\s+(январ[ьея]|феврал[ьея]|март[ае]?|апрел[ьея]|мая?|июн[ьея]|"
    r"июл[ьея]|август[ае]?|сентябр[ьея]|октябр[ьея]|ноябр[ьея]|декабр[ьея])"
    r"\s+(\d{4})",
    re.IGNORECASE,
)

# Номера договоров и актов: «№ 12/3-АБ», «No 7», «Договор № 1-С»
RE_DOC_NUMBER = re.compile(r"(?:№|N[оo°])\s*([\w/.\-]+)", re.IGNORECASE)

