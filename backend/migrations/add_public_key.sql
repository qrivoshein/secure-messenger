-- Добавляет колонку для хранения публичного ECDH-ключа пользователя (формат JWK).
-- Используется при сквозном шифровании E2E: приватный ключ хранится только
-- на устройстве клиента (IndexedDB), на сервер уходит только публичный.
-- Сервер ни общим ключом пары, ни приватным ключом участников не располагает.

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS public_key TEXT,
    ADD COLUMN IF NOT EXISTS public_key_updated_at TIMESTAMP;

-- Индекс не нужен: ключи запрашиваются по username (там уже UNIQUE).
